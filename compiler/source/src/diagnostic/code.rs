//! Stable rule identifiers shared by diagnostic producers and consumers.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DiagnosticCategory {
    Error,
    Warning,
    Note,
    Help,
    Internal,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DiagnosticRole {
    Cause,
    Note,
    Help,
}

impl DiagnosticRole {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Cause => "cause",
            Self::Note => "note",
            Self::Help => "help",
        }
    }
}

macro_rules! diagnostic_codes {
    ($($code:ident => $category:ident,)*) => {
        #[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, serde::Serialize, serde::Deserialize)]
        pub enum DiagnosticCode { $($code,)* }

        impl DiagnosticCode {
            pub const ALL: &'static [Self] = &[$(Self::$code,)*];

            pub const fn as_str(self) -> &'static str {
                match self { $(Self::$code => stringify!($code),)* }
            }

            pub const fn category(self) -> DiagnosticCategory {
                match self { $(Self::$code => DiagnosticCategory::$category,)* }
            }

            pub fn parse(value: &str) -> Option<Self> {
                match value { $(stringify!($code) => Some(Self::$code),)* _ => None }
            }
        }
    };
}

impl DiagnosticCode {
    pub const fn role(self) -> DiagnosticRole {
        match self.category() {
            DiagnosticCategory::Error | DiagnosticCategory::Internal => DiagnosticRole::Cause,
            DiagnosticCategory::Help => DiagnosticRole::Help,
            DiagnosticCategory::Note | DiagnosticCategory::Warning => DiagnosticRole::Note,
        }
    }
}

impl std::fmt::Display for DiagnosticCode {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(self.as_str())
    }
}

