#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn registry_round_trips_without_duplicate_or_legacy_codes() {
        let mut spellings = BTreeSet::new();
        let mut counts = [0; 5];
        for &code in DiagnosticCode::ALL {
            assert!(spellings.insert(code.as_str()));
            assert_eq!(DiagnosticCode::parse(code.as_str()), Some(code));
            let index = match code.category() {
                DiagnosticCategory::Error => 0,
                DiagnosticCategory::Warning => 1,
                DiagnosticCategory::Note => 2,
                DiagnosticCategory::Help => 3,
                DiagnosticCategory::Internal => 4,
            };
            counts[index] += 1;
            let number = code
                .as_str()
                .trim_start_matches(|c: char| c.is_ascii_uppercase());
            assert_eq!(number.len(), 4);
            assert!(number.bytes().all(|c| c.is_ascii_digit()));
        }
        assert_eq!(counts, [348, 15, 14, 30, 13]);
        for retired in ["SCOOPC_HIR_ERROR", "SLIB_WIRE_WRONG_TYPE", "E0000", "e0501"] {
            assert_eq!(DiagnosticCode::parse(retired), None);
        }
    }

    #[test]
    fn the_rule_determines_attachment_role() {
        assert_eq!(DiagnosticCode::E0501.role(), DiagnosticRole::Cause);
        assert_eq!(DiagnosticCode::ICE0601.role(), DiagnosticRole::Cause);
        assert_eq!(DiagnosticCode::N0002.role(), DiagnosticRole::Note);
        assert_eq!(DiagnosticCode::H0501.role(), DiagnosticRole::Help);
    }
}
